#!/usr/bin/env python3
"""Rebuild the checked-in Vulkan quad-index compute module (glslangValidator + spirv-val)."""
from pathlib import Path
import struct
import subprocess
import tempfile

here = Path(__file__).resolve().parent
with tempfile.TemporaryDirectory(prefix='totk-quad-spv-') as temp:
    output = Path(temp) / 'quad.spv'
    subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.1', '-Os', str(here / 'vk_quad_indices.comp'), '-o', str(output)], check=True)
    subprocess.run(['spirv-val', '--target-env', 'vulkan1.1', str(output)], check=True)
    data = output.read_bytes()
words = struct.unpack('<' + 'I' * (len(data) // 4), data)
lines = ['/* Generated by gen_vk_quad_indices.py from vk_quad_indices.comp. */', '#pragma once',
         'static const uint32_t vk_quad_indices_spv[] = {']
lines += ['    ' + ', '.join(f'0x{x:08x}u' for x in words[i:i+8]) + ',' for i in range(0, len(words), 8)]
lines += ['};', '']
(here / 'vk_quad_indices_spv.h').write_text('\n'.join(lines))
